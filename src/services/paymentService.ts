import crypto from 'crypto';

/**
 * GROVIA Payment Service Abstraction
 * Supports Razorpay Live Gateway, Webhooks, Signature Verification, Refunds,
 * alongside secure Demo Mode and Cash-on-Delivery (COD).
 */

export interface PaymentRequest {
  orderId: string;
  orderNumber: string;
  amount: number;
  currency: string;
  method: 'COD' | 'UPI' | 'CARD' | 'DEMO' | 'RAZORPAY';
  customer: {
    name: string;
    email: string;
    phone: string;
  };
}

export interface PaymentResponse {
  success: boolean;
  transactionId: string;
  provider: string;
  status: 'SUCCESS' | 'FAILED' | 'PENDING';
  message: string;
}

export interface RazorpayOrderPayload {
  amount: number; // in INR rupees
  currency?: string;
  receipt: string;
  notes?: Record<string, string>;
}

export interface SignatureVerificationPayload {
  razorpayOrderId: string;
  razorpayPaymentId: string;
  razorpaySignature: string;
}

export class PaymentService {
  /**
   * Check whether live Razorpay credentials are configured and not placeholders
   */
  static isConfigured(): boolean {
    const key = process.env.RAZORPAY_KEY_ID;
    const secret = process.env.RAZORPAY_KEY_SECRET;
    return Boolean(
      key &&
      secret &&
      key !== 'rzp_test_placeholder_key' &&
      secret !== 'rzp_test_placeholder_secret'
    );
  }

  /**
   * Get operational mode: LIVE (real credentials) vs DEMO_STANDBY
   */
  static getOperationalMode(): 'LIVE' | 'DEMO_STANDBY' {
    return this.isConfigured() && process.env.PAYMENT_MODE === 'LIVE'
      ? 'LIVE'
      : 'DEMO_STANDBY';
  }

  /**
   * Process generic checkout payment (COD, Demo, or Online initiation)
   */
  static async processPayment(req: PaymentRequest): Promise<PaymentResponse> {
    const isLiveGateway = this.getOperationalMode() === 'LIVE';

    if (req.method === 'COD') {
      return {
        success: true,
        transactionId: `COD_${Date.now()}_${Math.random().toString(36).substr(2, 6).toUpperCase()}`,
        provider: 'CASH_ON_DELIVERY',
        status: 'PENDING',
        message: 'Order placed with Cash on Delivery. Pay at your doorstep.',
      };
    }

    if (!isLiveGateway) {
      // Robust Demo / Test Payment Mode
      const txnId = `TXN_DEMO_${Date.now()}_${Math.random().toString(36).substr(2, 8).toUpperCase()}`;
      return {
        success: true,
        transactionId: txnId,
        provider: 'GROVIA_DEMO_GATEWAY',
        status: 'SUCCESS',
        message: `Verified demo payment of ₹${req.amount.toFixed(2)} via ${req.method}.`,
      };
    }

    // Live Gateway Transaction Token
    return {
      success: true,
      transactionId: `TXN_RZP_${Date.now()}`,
      provider: 'RAZORPAY',
      status: 'SUCCESS',
      message: 'Razorpay transaction successfully initialized.',
    };
  }

  /**
   * Server-Side Razorpay Order Creation
   */
  static async createRazorpayOrder(payload: RazorpayOrderPayload): Promise<{
    id: string;
    amount: number;
    currency: string;
    receipt: string;
    isLive: boolean;
  }> {
    const amountInPaise = Math.round(payload.amount * 100);
    const currency = payload.currency || 'INR';

    if (this.getOperationalMode() !== 'LIVE') {
      // Return safe mock order representation with real mathematical amounts
      return {
        id: `order_demo_${Date.now()}_${Math.random().toString(36).substr(2, 6)}`,
        amount: amountInPaise,
        currency,
        receipt: payload.receipt,
        isLive: false,
      };
    }

    // Live Razorpay API call
    const keyId = process.env.RAZORPAY_KEY_ID!;
    const keySecret = process.env.RAZORPAY_KEY_SECRET!;
    const authHeader = 'Basic ' + Buffer.from(`${keyId}:${keySecret}`).toString('base64');

    const res = await fetch('https://api.razorpay.com/v1/orders', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: authHeader,
      },
      body: JSON.stringify({
        amount: amountInPaise,
        currency,
        receipt: payload.receipt,
        notes: payload.notes || {},
      }),
    });

    if (!res.ok) {
      const err = await res.json();
      throw new Error(err.error?.description || 'Razorpay order creation failed');
    }

    const orderData = await res.json();
    return {
      id: orderData.id,
      amount: orderData.amount,
      currency: orderData.currency,
      receipt: orderData.receipt,
      isLive: true,
    };
  }

  /**
   * Server-Side Payment Signature Verification
   * HMAC SHA256 of `order_id|payment_id` against `RAZORPAY_KEY_SECRET`
   */
  static verifyPaymentSignature(payload: SignatureVerificationPayload): boolean {
    const secret = process.env.RAZORPAY_KEY_SECRET;
    if (!secret) return false;

    // Demo orders generated by standby mode pass verification if pattern matches
    if (payload.razorpayOrderId.startsWith('order_demo_') && this.getOperationalMode() === 'DEMO_STANDBY') {
      return true;
    }

    const hmac = crypto.createHmac('sha256', secret);
    hmac.update(`${payload.razorpayOrderId}|${payload.razorpayPaymentId}`);
    const expectedSignature = hmac.digest('hex');

    const expectedBuf = Buffer.from(expectedSignature, 'utf-8');
    const actualBuf = Buffer.from(payload.razorpaySignature, 'utf-8');

    if (expectedBuf.length !== actualBuf.length) {
      return false;
    }

    return crypto.timingSafeEqual(expectedBuf, actualBuf);
  }

  /**
   * Webhook Signature Verification
   */
  static verifyWebhookSignature(payloadString: string, signature: string, webhookSecret?: string): boolean {
    const secret = webhookSecret || process.env.RAZORPAY_WEBHOOK_SECRET;
    if (!secret || !signature) return false;

    try {
      const hmac = crypto.createHmac('sha256', secret);
      hmac.update(payloadString);
      const expected = hmac.digest('hex');

      const expectedBuf = Buffer.from(expected, 'utf-8');
      const actualBuf = Buffer.from(signature, 'utf-8');

      if (expectedBuf.length !== actualBuf.length) {
        return false;
      }

      return crypto.timingSafeEqual(expectedBuf, actualBuf);
    } catch {
      return false;
    }
  }

  /**
   * Process Refund Workflow
   */
  static async processRefund(paymentId: string, amount?: number, notes?: string): Promise<{
    refundId: string;
    status: 'PROCESSED' | 'FAILED';
    amount: number;
  }> {
    if (this.getOperationalMode() !== 'LIVE') {
      return {
        refundId: `rfnd_demo_${Date.now()}`,
        status: 'PROCESSED',
        amount: amount || 0,
      };
    }

    const keyId = process.env.RAZORPAY_KEY_ID!;
    const keySecret = process.env.RAZORPAY_KEY_SECRET!;
    const authHeader = 'Basic ' + Buffer.from(`${keyId}:${keySecret}`).toString('base64');

    const res = await fetch(`https://api.razorpay.com/v1/payments/${paymentId}/refund`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: authHeader,
      },
      body: JSON.stringify({
        amount: amount ? Math.round(amount * 100) : undefined,
        notes: { reason: notes || 'Customer order cancellation' },
      }),
    });

    if (!res.ok) {
      const err = await res.json();
      throw new Error(err.error?.description || 'Refund processing failed');
    }

    const refund = await res.json();
    return {
      refundId: refund.id,
      status: refund.status === 'processed' ? 'PROCESSED' : 'FAILED',
      amount: refund.amount / 100,
    };
  }
}
